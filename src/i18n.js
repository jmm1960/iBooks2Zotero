  function resolveLocale(...candidates) {
    const locale = candidates.find(value => typeof value === 'string' && /^[a-z]{2,3}(?:[-_][a-z0-9]+)*$/i.test(value.trim()));
    return locale && /^zh(?:[-_]|$)/i.test(locale.trim()) ? 'zh' : 'en';
  }
  function create(...candidates) {
    const locale = resolveLocale(...candidates);
    function t(key, params = {}) {
      const template = catalogs[locale][key] ?? catalogs.en[key];
      if (template === undefined) throw new Error('Unknown translation key: ' + key);
      return template.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
    }
    function error(value) {
      return value?.code && catalogs.en[value.code] ? t(value.code, value.params) : value?.message || String(value);
    }
    function apply(document) {
      document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
      for (const element of document.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
      for (const attribute of ['title', 'aria-label']) {
        for (const element of document.querySelectorAll('[data-i18n-' + attribute + ']')) element.setAttribute(attribute, t(element.getAttribute('data-i18n-' + attribute)));
      }
    }
    return {locale, t, error, apply};
  }
  return {create, resolveLocale, catalogs};
